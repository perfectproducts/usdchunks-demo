from pxr import Usd, UsdGeom, UsdShade, Sdf, Gf
st = Usd.Stage.CreateNew("ladder_preview.usda")
UsdGeom.SetStageUpAxis(st, "Y")
root = UsdGeom.Xform.Define(st, "/Preview")
mat = UsdShade.Material.Define(st, "/Preview/Looks/wood")
sh = UsdShade.Shader.Define(st, "/Preview/Looks/wood/pbr"); sh.CreateIdAttr("UsdPreviewSurface")
sh.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f).Set(Gf.Vec3f(0.45, 0.24, 0.10))
sh.CreateInput("roughness", Sdf.ValueTypeNames.Float).Set(0.6)
mat.CreateSurfaceOutput().ConnectToSource(sh.ConnectableAPI(), "surface")
gm = UsdShade.Material.Define(st, "/Preview/Looks/ground")
gs = UsdShade.Shader.Define(st, "/Preview/Looks/ground/pbr"); gs.CreateIdAttr("UsdPreviewSurface")
gs.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f).Set(Gf.Vec3f(0.35, 0.37, 0.38))
gm.CreateSurfaceOutput().ConnectToSource(gs.ConnectableAPI(), "surface")
for i, (f, x) in enumerate([("ladder.usda", -2.1), ("ladder_short.usda", -0.9), ("ladder_tall_wide.usda", 0.45), ("ladder_dense.usda", 1.9)]):
    p = UsdGeom.Xform.Define(st, f"/Preview/L{i}")
    p.GetPrim().GetReferences().AddReference(f, "/World")
    p.AddTranslateOp().Set(Gf.Vec3d(x, 0, 0))
    UsdShade.MaterialBindingAPI.Apply(p.GetPrim()).Bind(mat)
g = UsdGeom.Mesh.Define(st, "/Preview/ground")
g.CreatePointsAttr([(-3.2,0,-1.5),(3.2,0,-1.5),(3.2,0,1.5),(-3.2,0,1.5)]); g.CreateFaceVertexCountsAttr([4]); g.CreateFaceVertexIndicesAttr([0,3,2,1])
UsdShade.MaterialBindingAPI.Apply(g.GetPrim()).Bind(gm)
st.SetDefaultPrim(root.GetPrim()); st.Save()
